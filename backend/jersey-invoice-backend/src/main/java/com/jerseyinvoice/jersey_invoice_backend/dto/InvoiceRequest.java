package com.jerseyinvoice.jersey_invoice_backend.dto;

import jakarta.validation.Valid;
import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;

/** Data sent by a client when creating an invoice. The invoice number is generated by the backend. */
public record InvoiceRequest(
        @NotNull LocalDate date,
        @PositiveOrZero @Digits(integer = 10, fraction = 2) BigDecimal postagePrice,
        @NotNull @Valid CustomerRequest customer,
        @NotEmpty List<@NotNull @Valid JobRequest> jobs,
        List<@NotNull @Valid SpecialRequest> specialRequests
) {
    public record CustomerRequest(
            @NotBlank @Size(max = 255) String name,
            @Size(max = 255) String companyName,
            @Email @Size(max = 255) String email,
            @NotBlank @Size(max = 255) String phone,
            @NotBlank @Size(max = 1000) String address
    ) {}

    public record JobRequest(
            @NotNull JobType jobType,
            @NotBlank @Size(max = 255) String jobName,
            @NotBlank @Size(max = 255) String design,
            @NotNull @Valid Sizes sizes,
            @Size(max = 255) String material,
            @Size(max = 255) String collar,
            @Size(max = 255) String sleeve,
            @Size(max = 255) String nameset,
            @Size(max = 255) String cutting,
            @Size(max = 255) String piping,
            List<@NotNull @Valid SpecialRequest> specialRequests
    ) {
        @AssertTrue(message = "Standard jobs require material, collar, sleeve, nameset, cutting and piping")
        public boolean isStandardDetailsValid() {
            return jobType != JobType.STANDARD || (hasText(material) && hasText(collar)
                    && hasText(sleeve) && hasText(nameset) && hasText(cutting) && hasText(piping));
        }

        private static boolean hasText(String value) {
            return value != null && !value.isBlank();
        }
    }

    /** Omitted size quantities default to zero. The form also supports 7XL. */
    public record Sizes(
            @PositiveOrZero Integer xs,
            @PositiveOrZero Integer s,
            @PositiveOrZero Integer m,
            @PositiveOrZero Integer l,
            @PositiveOrZero Integer xl,
            @PositiveOrZero Integer xl2,
            @PositiveOrZero Integer xl3,
            @PositiveOrZero Integer xl4,
            @PositiveOrZero Integer xl5,
            @PositiveOrZero Integer xl6,
            @PositiveOrZero Integer xl7
    ) {
        public Sizes {
            xs = xs == null ? 0 : xs;
            s = s == null ? 0 : s;
            m = m == null ? 0 : m;
            l = l == null ? 0 : l;
            xl = xl == null ? 0 : xl;
            xl2 = xl2 == null ? 0 : xl2;
            xl3 = xl3 == null ? 0 : xl3;
            xl4 = xl4 == null ? 0 : xl4;
            xl5 = xl5 == null ? 0 : xl5;
            xl6 = xl6 == null ? 0 : xl6;
            xl7 = xl7 == null ? 0 : xl7;
        }
        @AssertTrue(message = "A job must have at least one jersey")
        public boolean isQuantityPresent() {
            return (long) xs + s + m + l + xl + xl2 + xl3 + xl4 + xl5 + xl6 + xl7 > 0;
        }
    }

    public record SpecialRequest(
            @NotBlank @Size(max = 255) String name,
            @NotNull @PositiveOrZero @Digits(integer = 10, fraction = 2) BigDecimal price,
            @NotNull ChargeType chargeType
    ) {}

    public enum JobType {
        STANDARD, PAINTBALL
    }

    public enum ChargeType {
        PCS, ONE
    }
}
